export type CounterCategory = 'General' | 'People & animals' | 'Objects' | 'Time' | 'Events & places'

export interface JapaneseCounter {
  id: string
  suffix: string
  reading: string
  category: CounterCategory
  counts: string
  example: {
    japanese: string
    reading: string
    english: string
  }
  note: string
}

export interface CounterQuiz {
  /** Japanese sentence with one counter-sized blank. */
  prompt: string
  answer: string
  options: readonly string[]
  completed: string
  reading: string
  english: string
}

