import type { SentenceExercise } from './sentenceExercises'
import type { JlptLevel } from '../lib/types'

function grammarSentence(
  id: string,
  jlpt: JlptLevel,
  english: string,
  segments: string[],
  readings: string[],
): SentenceExercise {
  return {
    id: `sent-grammar-${id}`,
    type: 'sentence-builder',
    segments,
    segmentReadings: readings,
    segmentMeanings: segments.map(() => ''),
    english,
    jlpt,
  }
}

